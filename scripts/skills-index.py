#!/usr/bin/env python3
"""The skills index: one line per skill and command, grouped by job.

Usage:
  skills-index.py brief [mine|upstream|commands]   print the index (default: mine)
  skills-index.py readme                           rewrite the marked region of README.md
  skills-index.py check                            exit 1 when an entry is missing or README is stale
  skills-index.py shorten                          filter: cut `name — description` lines on stdin to one line

Where a line comes from:
  - a skill's own frontmatter: `summary:` and `group:` in skills/<name>/SKILL.md
  - the sidecar, scripts/skills-index-sidecar.toml, for what cannot carry its own:
    skills tracked in upstream (the pre-commit guard blocks edits to them) and the
    slash commands in ~/.claude/commands, which live in another repo.

Python 3.9 compatible (macOS system python3), so the sidecar is read by a small
parser for the subset it uses, not tomllib.
"""

import os
import re
import subprocess
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.realpath(__file__)))
SKILLS_DIR = os.path.join(REPO_ROOT, "skills")
SKILL_FILE = "SKILL.md"
SIDECAR_PATH = os.path.join(REPO_ROOT, "scripts", "skills-index-sidecar.toml")
README_PATH = os.path.join(REPO_ROOT, "README.md")
COMMANDS_DIR_ENV = "SKILLS_INDEX_COMMANDS_DIR"
DEFAULT_COMMANDS_DIR = os.path.join(os.path.expanduser("~"), ".claude", "commands")

README_BEGIN = "<!-- skills-index:begin (generated by `make readme-index` from each skill's summary: and group: — do not edit by hand) -->"
README_END = "<!-- skills-index:end -->"
README_BEGIN_PREFIX = "<!-- skills-index:begin"

SUMMARY_MAX_CHARS = 120
SHORTEN_MAX_CHARS = 110

# The groups, in the order they are listed. A skill's `group:` must be one of these
# keys; adding a group is adding a line here.
GROUPS = (
    ("session", "Session — where things stand, what to pick up, wrapping up"),
    ("backlog", "Backlog — capturing work and working the queue"),
    ("design", "Design and docs — thinking, the design/ directory, writing"),
    ("project", "Project setup"),
    ("code", "Code — branches, quality, building"),
    ("delegate", "Delegation and autonomy"),
    ("tooling", "Claude setup — skills, commands, CLAUDE.md"),
)
GROUP_KEYS = tuple(key for key, _title in GROUPS)
COMMANDS_TITLE = "Commands — in ~/.claude/commands (the dot-claude repo), no context cost until typed"
OTHER_SOURCES_LINE = (
    "gstack and plugin skills are not indexed here: `/skills-list gstack brief` and "
    "`/skills-list plugins brief` list them from their own descriptions."
)

FRONTMATTER_FENCE = "---"
SIDECAR_TABLE = re.compile(r"^\[(skills|commands)\.([A-Za-z0-9_-]+)\]$")
SIDECAR_PAIR = re.compile(r'^(summary|group)\s*=\s*"(.*)"$')
FRONTMATTER_PAIR = re.compile(r"^(summary|group|description):\s*(.*)$")


class SkillsIndexError(RuntimeError):
    """A file the index is built from cannot be read as the index expects."""


def unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    return value


def read_frontmatter(path):
    """summary / group / description from a markdown file's frontmatter ({} if none)."""
    fields = {}
    try:
        with open(path, encoding="utf-8") as handle:
            lines = handle.read().split("\n")
    except OSError:
        return fields
    if not lines or lines[0].strip() != FRONTMATTER_FENCE:
        return fields
    for line in lines[1:]:
        if line.strip() == FRONTMATTER_FENCE:
            break
        pair = FRONTMATTER_PAIR.match(line)
        if pair:
            fields[pair.group(1)] = unquote(pair.group(2))
    return fields


def read_sidecar():
    """{'skills': {name: {summary, group}}, 'commands': {name: {summary}}}"""
    entries = {"skills": {}, "commands": {}}
    if not os.path.isfile(SIDECAR_PATH):
        return entries
    current = None
    with open(SIDECAR_PATH, encoding="utf-8") as handle:
        for number, raw in enumerate(handle, 1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            table = SIDECAR_TABLE.match(line)
            if table:
                current = entries[table.group(1)].setdefault(table.group(2), {})
                continue
            pair = SIDECAR_PAIR.match(line)
            if pair and current is not None:
                current[pair.group(1)] = pair.group(2)
                continue
            raise SkillsIndexError(
                "%s:%d: not a [skills.<name>] / [commands.<name>] table or a summary/group line: %s"
                % (os.path.relpath(SIDECAR_PATH, REPO_ROOT), number, line)
            )
    return entries


def skill_names():
    return sorted(
        name
        for name in os.listdir(SKILLS_DIR)
        if os.path.isfile(os.path.join(SKILLS_DIR, name, SKILL_FILE))
    )


def upstream_skill_names():
    """Skills tracked in upstream/main; empty when there is no such remote."""
    try:
        listing = subprocess.run(
            [
                "git",
                "-C",
                REPO_ROOT,
                "ls-tree",
                "-r",
                "--name-only",
                "upstream/main",
                "skills/",
            ],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (subprocess.CalledProcessError, FileNotFoundError):
        return set()
    return {
        parts[1]
        for parts in (line.split("/") for line in listing.splitlines())
        if len(parts) >= 3
    }


def collect_skills(sidecar):
    """([(name, summary, group)], [problem strings])"""
    rows, problems = [], []
    for name in skill_names():
        own = read_frontmatter(os.path.join(SKILLS_DIR, name, SKILL_FILE))
        side = sidecar["skills"].get(name, {})
        where = "skills/%s/%s" % (name, SKILL_FILE)
        if ("summary" in own or "group" in own) and side:
            problems.append(
                "%s: has summary:/group: in its frontmatter and an entry in the sidecar; keep one"
                % name
            )
        summary = own.get("summary") or side.get("summary")
        group = own.get("group") or side.get("group")
        if not summary:
            problems.append(
                "%s: no summary: (add it to %s, or to the sidecar if the skill is upstream-tracked)"
                % (name, where)
            )
        elif len(summary) > SUMMARY_MAX_CHARS:
            problems.append(
                "%s: summary is %d characters, over %d"
                % (name, len(summary), SUMMARY_MAX_CHARS)
            )
        if not group:
            problems.append(
                "%s: no group: (one of: %s)" % (name, ", ".join(GROUP_KEYS))
            )
        elif group not in GROUP_KEYS:
            problems.append(
                "%s: group '%s' is not one of: %s"
                % (name, group, ", ".join(GROUP_KEYS))
            )
        rows.append((name, summary or "", group or ""))
    for name in sorted(set(sidecar["skills"]) - set(skill_names())):
        problems.append("%s: in the sidecar, but there is no skills/%s/" % (name, name))
    return rows, problems


def commands_dir():
    return os.environ.get(COMMANDS_DIR_ENV) or DEFAULT_COMMANDS_DIR


def installed_commands():
    """{name: description-or-first-line} for the command files on this machine."""
    found = {}
    directory = commands_dir()
    if not os.path.isdir(directory):
        return found
    for filename in sorted(os.listdir(directory)):
        if not filename.endswith(".md"):
            continue
        path = os.path.join(directory, filename)
        description = read_frontmatter(path).get("description")
        if not description:
            try:
                with open(path, encoding="utf-8") as handle:
                    description = next(
                        (
                            line.strip()
                            for line in handle
                            if line.strip() and line.strip() != FRONTMATTER_FENCE
                        ),
                        "",
                    )
            except OSError:
                description = ""
        found[filename[:-3]] = description
    return found


def collect_commands(sidecar):
    """Rows for the brief listing: the sidecar's commands, then any command file on
    this machine the sidecar does not know, marked so. ([(name, summary)], [notes])"""
    rows = [
        (name, entry.get("summary", ""))
        for name, entry in sorted(sidecar["commands"].items())
    ]
    notes = []
    for name, description in installed_commands().items():
        if name not in sidecar["commands"]:
            rows.append(
                (
                    name,
                    shorten(description)
                    + "  (not in the index: add [commands.%s] to the sidecar)" % name,
                )
            )
            notes.append(
                "command %s is in %s but not in the sidecar" % (name, commands_dir())
            )
    return rows, notes


def shorten(text, limit=SHORTEN_MAX_CHARS):
    """First sentence of a description, cut to one line."""
    text = " ".join(text.split()).strip("\"'")
    first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    if len(first) > limit:
        first = first[: limit - 1].rstrip() + "…"
    return first


def grouped(rows):
    for key, title in GROUPS:
        members = [(name, summary) for name, summary, group in rows if group == key]
        if members:
            yield title, members
    stray = [
        (name, summary) for name, summary, group in rows if group not in GROUP_KEYS
    ]
    if stray:
        yield "No group", stray


def print_rows(title, members, prefix="/"):
    width = max(len(name) for name, _summary in members) + len(prefix)
    print(title)
    for name, summary in members:
        print("  %-*s  %s" % (width, prefix + name, summary or "(no summary)"))
    print("")


def cmd_brief(scope):
    sidecar = read_sidecar()
    if scope in ("mine", "upstream"):
        rows, _problems = collect_skills(sidecar)
        if scope == "upstream":
            upstream = upstream_skill_names()
            rows = [row for row in rows if row[0] in upstream]
        for title, members in grouped(rows):
            print_rows(title, members)
    if scope in ("mine", "commands"):
        command_rows, _notes = collect_commands(sidecar)
        if command_rows:
            print_rows(COMMANDS_TITLE, command_rows)
    return 0


def readme_region(sidecar):
    rows, _problems = collect_skills(sidecar)
    out = [README_BEGIN, ""]
    for title, members in grouped(rows):
        out += ["### %s" % title, "", "| Skill | What it does |", "| --- | --- |"]
        out += [
            "| `%s` | %s |" % (name, summary.replace("|", "\\|"))
            for name, summary in members
        ]
        out.append("")
    commands = sorted(sidecar["commands"].items())
    if commands:
        out += [
            "### %s" % COMMANDS_TITLE,
            "",
            "| Command | What it does |",
            "| --- | --- |",
        ]
        out += [
            "| `/%s` | %s |" % (name, entry.get("summary", "").replace("|", "\\|"))
            for name, entry in commands
        ]
        out.append("")
    out += [OTHER_SOURCES_LINE, "", README_END]
    return out


def split_readme():
    with open(README_PATH, encoding="utf-8") as handle:
        lines = handle.read().split("\n")
    begin = [i for i, line in enumerate(lines) if line.startswith(README_BEGIN_PREFIX)]
    end = [i for i, line in enumerate(lines) if line.strip() == README_END]
    if len(begin) != 1 or len(end) != 1 or end[0] < begin[0]:
        raise SkillsIndexError(
            "README.md: expected one '%s …' line and one '%s' line after it"
            % (README_BEGIN_PREFIX, README_END)
        )
    return lines, begin[0], end[0]


def cmd_readme():
    lines, begin, end = split_readme()
    updated = lines[:begin] + readme_region(read_sidecar()) + lines[end + 1 :]
    if updated == lines:
        print("README.md § Skills is up to date.")
        return 0
    with open(README_PATH, "w", encoding="utf-8") as handle:
        handle.write("\n".join(updated))
    print("README.md § Skills rewritten.")
    return 0


def cmd_check():
    sidecar = read_sidecar()
    _rows, problems = collect_skills(sidecar)
    for name, entry in sorted(sidecar["commands"].items()):
        if not entry.get("summary"):
            problems.append("command %s: no summary in the sidecar" % name)
    lines, begin, end = split_readme()
    if lines[begin : end + 1] != readme_region(sidecar):
        problems.append(
            "README.md § Skills is out of date: run `make readme-index` and stage README.md"
        )
    _command_rows, notes = collect_commands(sidecar)
    for note in notes:
        print("skills-index: note: %s" % note, file=sys.stderr)
    if problems:
        print("skills-index: %d problem(s):" % len(problems), file=sys.stderr)
        for problem in problems:
            print("  - %s" % problem, file=sys.stderr)
        return 1
    print(
        "skills-index: ok (%d skills, %d commands)"
        % (len(skill_names()), len(sidecar["commands"]))
    )
    return 0


def cmd_shorten():
    for raw in sys.stdin:
        line = raw.rstrip("\n")
        head, separator, description = line.partition(" — ")
        print(head + separator + shorten(description) if separator else line)
    return 0


def main(argv):
    command = argv[1] if len(argv) > 1 else ""
    try:
        if command == "brief":
            scope = argv[2] if len(argv) > 2 else "mine"
            if scope not in ("mine", "upstream", "commands"):
                print(
                    "skills-index: brief takes mine, upstream or commands, not '%s'"
                    % scope,
                    file=sys.stderr,
                )
                return 2
            return cmd_brief(scope)
        if command == "readme":
            return cmd_readme()
        if command == "check":
            return cmd_check()
        if command == "shorten":
            return cmd_shorten()
    except SkillsIndexError as error:
        print("skills-index: %s" % error, file=sys.stderr)
        return 1
    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
